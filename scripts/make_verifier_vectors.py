"""
Generate cross-implementation test vectors for the browser verifier (web/test/vectors.json).

The Python implementation is the reference. This script builds records with it - signed, unsigned,
pending-timestamped and Bitcoin-attested (against a *fabricated* block header; nothing touches the
network) - and the JS tests must reach the same verdicts and the same canonical bytes.

The signing key is derived from a public constant: it is a TEST key and signs nothing real.

    python scripts/make_verifier_vectors.py
"""

from __future__ import annotations

import base64
import hashlib
import json
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from bitcoin.core import CBlockHeader  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ed25519  # noqa: E402
from opentimestamps.core import notary, op  # noqa: E402
from opentimestamps.core.timestamp import DetachedTimestampFile, Timestamp  # noqa: E402

from src.anchors import ots  # noqa: E402
from src.attest import build_attestation_payload  # noqa: E402
from src.evidence.hashing import canonicalize  # noqa: E402
from src.evidence.record import seal  # noqa: E402
from src.trust import sign_record  # noqa: E402

OUT = ROOT / "web" / "test" / "vectors.json"

CANONICAL_CASES = [
    {"b": 1, "a": [True, False, None], "c": {"z": "x", "y": "é€"}},
    {"\U0001f600": 1, "": 2, "a": 3},  # UTF-16 order differs from code point order here
    {"s": 'quote " backslash \\ tab \t newline \n ctrl \u0001 slash /'},
    {"n": [0, -1, 9007199254740991, -9007199254740991]},
    {},
    [],
]


def main() -> None:
    img = np.zeros((48, 48, 3), np.uint8)
    img[:, :, 0] = np.linspace(0, 255, 48, dtype=np.uint8)[None, :]
    img[10:30, 10:30, 2] = 200
    ok, png = cv2.imencode(".png", img)
    assert ok
    image_bytes = png.tobytes()
    tmp = ROOT / "output" / "_vector_image.png"
    tmp.parent.mkdir(exist_ok=True)
    tmp.write_bytes(image_bytes)
    try:
        payload = build_attestation_payload(tmp, created_at="2026-01-01T00:00:00Z")
    finally:
        tmp.unlink(missing_ok=True)

    key = ed25519.Ed25519PrivateKey.from_private_bytes(hashlib.sha256(b"faceproof-test-vector-key").digest())
    signed = sign_record(seal(payload), key)
    vhash = signed["integrity"]["verification_hash"]

    # Pending timestamp
    digest = bytes.fromhex(vhash[2:])
    ts = Timestamp(digest)
    stamped = ts.ops.add(op.OpAppend(b"nonce-bytes")).ops.add(op.OpSHA256())
    stamped.attestations.add(notary.PendingAttestation("https://alice.btc.calendar.opentimestamps.org"))
    pending = ots._anchor_dict(
        DetachedTimestampFile(op.OpSHA256(), ts), digest, ["https://alice.btc.calendar.opentimestamps.org"], "pending"
    )

    # Bitcoin-attested timestamp with a fabricated header whose Merkle root is the commitment
    ts2 = Timestamp(digest)
    commitment_node = ts2.ops.add(op.OpAppend(b"nonce-bytes")).ops.add(op.OpSHA256())
    commitment = commitment_node.msg
    commitment_node.attestations.add(notary.BitcoinBlockHeaderAttestation(800_000))
    header = CBlockHeader(
        nVersion=4, hashPrevBlock=b"\x00" * 32, hashMerkleRoot=commitment, nTime=1_700_000_000, nBits=0x1D00FFFF
    ).serialize()
    attested = ots._anchor_dict(DetachedTimestampFile(op.OpSHA256(), ts2), digest, [], "bitcoin_attested")

    vectors = {
        "note": "Generated by scripts/make_verifier_vectors.py. TEST key, FABRICATED block header; not evidence.",
        "image_b64": base64.b64encode(image_bytes).decode(),
        "public_key": signed["signature"]["public_key"],
        "header_height": 800_000,
        "header_hex": header.hex(),
        "records": {
            "signed_unanchored": signed,
            "signed_pending": {**signed, "anchor": pending},
            "signed_attested": {**signed, "anchor": attested},
        },
        "canonical": [{"value": c, "canonical": canonicalize(c).decode("utf-8")} for c in CANONICAL_CASES],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(vectors, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
